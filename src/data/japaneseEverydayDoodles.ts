import type { GirlSketch } from '../core/types';
import { createTimedStrokes } from '../lib/playback';

type Point = readonly [number, number];
type Path = readonly Point[];
const line = (...points: Point[]): Path => points;
const oval = (x: number, y: number, rx: number, ry: number): Path =>
  Array.from({ length: 19 }, (_, i): Point => {
    const angle = i * Math.PI / 9;
    const wobble = 1 + .025 * Math.sin(angle * 3 + x * 5);
    return [x + rx * Math.cos(angle) * wobble, y + ry * Math.sin(angle) * wobble];
  });
function doodle(id: string, word: string, readability: 'safe' | 'soft', paths: readonly Path[]): GirlSketch {
  const fullId = `shizuku-ja-everyday-${id}-v01`;
  // Small deterministic bow on long edges; no text, fill, faces or randomness.
  const drawn = paths.map((path, index) => path.flatMap((point, i): Point[] => {
    if (!i) return [point];
    const previous = path[i - 1];
    const dx = point[0] - previous[0], dy = point[1] - previous[1];
    if (Math.hypot(dx, dy) < .09) return [point];
    const bend = .018 * Math.sin(index * 1.7 + i);
    return [[(point[0] + previous[0]) / 2 - dy * bend, (point[1] + previous[1]) / 2 + dx * bend], point];
  }));
  return { id: fullId, word, readability, durationMs: 1200, strokes: createTimedStrokes(fullId, drawn, 1200) };
}

