type Point = readonly [number, number];
type Path = readonly Point[];
// Small, deliberately uneven contours, with no written hints. These are original
// authored vectors, not traced Quick Draw samples or recognition fixtures.
const oval = (x: number, y: number, rx: number, ry: number): Path => Array.from({ length: 17 }, (_, i) => {
  const angle = i / 16 * Math.PI * 2;
  const wobble = 1 + .025 * Math.sin(angle * 3);
  return [x + Math.cos(angle) * rx * wobble, y + Math.sin(angle) * ry * wobble] as Point;
});
const line = (...points: Point[]): Path => points;
