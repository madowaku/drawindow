import type { GirlSketch } from '../core/types';
import { createTimedStrokes } from '../lib/playback';

type Point = readonly [number, number];
type Path = readonly Point[];
const line = (...points: Point[]): Path => points;
const ellipse = (x: number, y: number, rx: number, ry: number): Path =>
  Array.from({ length: 17 }, (_, i): Point => {
    const t = i * Math.PI / 8;
    return [x + rx * Math.cos(t), y + ry * Math.sin(t)];
  });
const rect = (x1: number, y1: number, x2: number, y2: number): Path =>
  line([x1,y1],[x2,y1],[x2,y2],[x1,y2],[x1,y1]);
const circle = (x: number, y: number, r: number): Path => ellipse(x,y,r,r);

/**
 * Hand-authored, uncluttered finger-drawn silhouettes on a unit-square canvas.
 * Labels are phonetic kana only. SAFE is an internal maker judgement, not a
 * measured blind recognition rate; SOFT denotes visual/lexical ambiguity.
 * Every candidate needs first-time player review before public release.
 */
function doodle(id: string, word: string, readability: 'safe' | 'soft', paths: readonly Path[]): GirlSketch {
  const fullId = 'shizuku-ja-' + id + '-v01';
  return { id: fullId, word, readability, durationMs: 1200,
    strokes: createTimedStrokes(fullId, paths, 1200) };
}

